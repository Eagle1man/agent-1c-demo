# -*- coding: utf-8 -*-
import os
path = os.path.join(os.path.dirname(__file__), "web_app.py")
with open(path, "a", encoding="utf-8") as f:
    f.write("    def _process_message(self, text):\n")
    f.write("        lower = text.lower()\n")
    f.write("        agent_id = CURRENT_AGENT\n")
    f.write("        for a in AGENTS:\n")
    f.write('            if a["name"].lower() in lower or a["id"] in lower:\n')
    f.write("                agent_id = a[\"id\"]\n")
    f.write("                break\n")
    f.write('        AGENT_STATUS[agent_id] = "working"\n')
    f.write("        time.sleep(0.3)\n")
    f.write("        task_id = str(uuid.uuid4())[:8]\n")
    f.write('        icon = next((a["avatar"] for a in AGENTS if a["id"] == agent_id), "🤖")\n')
    f.write('        task = {"id": task_id, "subject": text[:50], "detail": f"Обработано агентом {agent_id}", "icon": icon, "status": "ok", "time": datetime.now().strftime("%H:%M:%S"), "agent": agent_id}\n')
    f.write("        TASK_QUEUE.append(task)\n")
    f.write('        if "связ" in lower or "проверь" in lower:\n')
    f.write('            result = {"type": "result", "title": "Проверка связи", "text": "✅ Связь с 1С установлена. Мост АгентМост отчитался.", "agent": agent_id}\n')
    f.write('        elif "остаток" in lower or "склад" in lower or "товар" in lower:\n')
    f.write('            result = {"type": "result", "title": "Остатки на складе", "text": "📦 Кладовщик сверяет остатки. Товаров на складе: 1577 шт.", "agent": agent_id}\n')
    f.write('        elif "задолжен" in lower or "контрагент" in lower or "долг" in lower:\n')
    f.write('            result = {"type": "result", "title": "Задолженность контрагентов", "text": "📊 Бухгалтер проверяет остатки по счетам.", "agent": agent_id}\n')
    f.write('        elif "документ" in lower or "созд" in lower or "налк" in lower:\n')
    f.write('            result = {"type": "pending", "title": "Требуется подтверждение", "text": "📝 Агент требует вашего решения перед созданием документа.", "agent": agent_id, "token": str(uuid.uuid4())[:8]}\n')
    f.write("        else:\n")
    f.write('            result = {"type": "result", "title": "Запрос принят", "text": "🤖 Запрос обработан в системе мультиагентов.", "agent": agent_id}\n')
    f.write('        AGENT_STATUS[agent_id] = "done"\n')
    f.write("        return result\n")
    f.write("\n")
    f.write("def main():\n")
    f.write("    ap = argparse.ArgumentParser()\n")
    f.write('    ap.add_argument("--mock", action="store_true")\n')
    f.write('    ap.add_argument("--no-mock", action="store_true")\n')
    f.write('    ap.add_argument("--exchange", default=None)\n')
    f.write('    ap.add_argument("--port", type=int, default=8080)\n')
    f.write("    args = ap.parse_args()\n")
    f.write("    cfg = _load_config()\n")
    f.write('    exch = Path(args.exchange) if args.exchange else resolve_exchange(cfg.get("exchange_path", "..\\\\exchange"))\n')
    f.write("    Handler.exchange = exch\n")
    f.write('    bridge = Bridge(exch, user="демо-пользователь")\n')
    f.write("    use_mock = args.mock or (not args.no_mock)\n")
    f.write("    if use_mock:\n")
    f.write("        from mock_bridge import Mock1C\n")
    f.write("        Handler.mock = Mock1C(exch).start()\n")
    f.write("        Handler.is_mock = True\n")
    f.write("    Handler.bridge = bridge\n")
    f.write("    global EXCHANGE_PATH\n")
    f.write("    EXCHANGE_PATH = str(exch)\n")
    f.write('    srv = ThreadingHTTPServer(("127.0.0.1", args.port), Handler)\n')
    f.write('    print(f"АгентМост 2.0: http://127.0.0.1:{args.port}  (exchange: {exch}, mock={bool(Handler.mock)})")\n')
    f.write("    try:\n")
    f.write("        srv.serve_forever()\n")
    f.write("    except KeyboardInterrupt:\n")
    f.write("        pass\n")
    f.write("    finally:\n")
    f.write("        if Handler.mock:\n")
    f.write("            Handler.mock.stop()\n")
    f.write("\n")
    f.write('if __name__ == "__main__":\n')
    f.write("    main()\n")
