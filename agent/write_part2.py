# -*- coding: utf-8 -*-
import os
path = os.path.join(os.path.dirname(__file__), "web_app.py")
with open(path, "a", encoding="utf-8") as f:
    f.write("class Handler(BaseHTTPRequestHandler):\n")
    f.write("    exchange = None\n")
    f.write("    mock = None\n")
    f.write("    bridge = None\n")
    f.write("    is_mock = False\n")
    f.write("    mode_lock = threading.Lock()\n")
    f.write("\n")
    f.write("    def log_message(self, format, *args):\n")
    f.write("        return\n")
    f.write("\n")
    f.write("    def _send_json(self, data, code=200):\n")
    f.write("        body = json.dumps(data, ensure_ascii=False).encode(\"utf-8\")\n")
    f.write("        self.send_response(code)\n")
    f.write("        self.send_header(\"Content-Type\", \"application/json; charset=utf-8\")\n")
    f.write("        self.send_header(\"Content-Length\", str(len(body)))\n")
    f.write("        self.end_headers()\n")
    f.write("        self.wfile.write(body)\n")
    f.write("\n")
    f.write("    def _send_file(self, filepath, content_type):\n")
    f.write("        data = filepath.read_bytes()\n")
    f.write("        self.send_response(200)\n")
    f.write("        self.send_header(\"Content-Type\", content_type)\n")
    f.write("        self.send_header(\"Content-Length\", str(len(data)))\n")
    f.write("        self.end_headers()\n")
    f.write("        self.wfile.write(data)\n")
    f.write("\n")
    f.write("    def do_GET(self):\n")
    f.write("        path = urlparse(self.path).path\n")
    f.write('        if path == "/api/agents":\n')
    f.write('            self._send_json({"agents": AGENTS, "status": AGENT_STATUS})\n')
    f.write("            return\n")
    f.write('        if path == "/api/tasks":\n')
    f.write('            self._send_json({"tasks": TASK_QUEUE})\n')
    f.write("            return\n")
    f.write('        if path == "/api/stats":\n')
    f.write('            self._send_json({"agents": len(AGENTS), "tasks": len(TASK_QUEUE), "errors": 0, "confirmations": 0, "validation": VALIDATION_RESULT})\n')
    f.write("            return\n")
    f.write('        if path == "/api/history":\n')
    f.write('            self._send_json({"history": CHAT_HISTORY[-20:]})\n')
    f.write("            return\n")
    f.write('        static_map = {"/": "index.html", "/index.html": "index.html", "/style.css": "style.css", "/app.js": "app.js"}\n')
    f.write("        filename = static_map.get(path)\n")
    f.write("        if filename is None:\n")
    f.write("            self.send_error(404)\n")
    f.write("            return\n")
    f.write("        filepath = STATIC_DIR / filename\n")
    f.write("        if not filepath.exists():\n")
    f.write("            self.send_error(404)\n")
    f.write("            return\n")
    f.write("        ext = filepath.suffix\n")
    f.write('        ctype = {"html": "text/html; charset=utf-8", "css": "text/css; charset=utf-8", "js": "application/javascript; charset=utf-8"}.get(ext, "application/octet-stream")\n')
    f.write("        self._send_file(filepath, ctype)\n")
    f.write("\n")
    f.write("    def do_POST(self):\n")
    f.write("        path = urlparse(self.path).path\n")
    f.write('        length = int(self.headers.get("Content-Length", 0))\n')
    f.write("        body = self.rfile.read(length).decode(\"utf-8\")\n")
    f.write('        if path == "/api/chat":\n')
    f.write("            try:\n")
    f.write("                data = json.loads(body) if body else {}\n")
    f.write("            except Exception:\n")
    f.write("                data = {}\n")
    f.write('            text = data.get("message", "")\n')
    f.write("            if not text:\n")
    f.write('                self._send_json({"error": "empty message"}, 400)\n')
    f.write("                return\n")
    f.write('            CHAT_HISTORY.append({"sender": "user", "text": text, "ts": datetime.now().isoformat()})\n')
    f.write("            resp = self._process_message(text)\n")
    f.write('            CHAT_HISTORY.append({"sender": "bot", **resp, "ts": datetime.now().isoformat()})\n')
    f.write("            self._send_json(resp)\n")
    f.write("            return\n")
    f.write('        if path == "/api/confirm":\n')
    f.write("            try:\n")
    f.write("                data = json.loads(body) if body else {}\n")
    f.write("            except Exception:\n")
    f.write("                data = {}\n")
    f.write('            answer = data.get("answer", "no")\n')
    f.write('            CHAT_HISTORY.append({"sender": "user", "text": f"Подтверждение: {answer}", "ts": datetime.now().isoformat()})\n')
    f.write('            resp = {"type": "result", "title": "Подтверждение", "text": f"Действие {answer} для агента {data.get(\'agent\', \'система\')}."}\n')
    f.write('            CHAT_HISTORY.append({"sender": "bot", **resp, "ts": datetime.now().isoformat()})\n')
    f.write("            self._send_json(resp)\n")
    f.write("            return\n")
    f.write("        self.send_error(404)\n")
    f.write("\n")
print("Part 2 written")
