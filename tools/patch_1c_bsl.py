from pathlib import Path

P = Path(r"C:\Users\diorl\.cline\data\workspaces\chat\agent-1c-demo\1c\АгентМост.bsl")
text = P.read_text(encoding="utf-8-sig")
if "ПроверитьФразуДиалога" in text:
    print("уже пропатчено")
    raise SystemExit(0)

# --- 1) в ПриОткрытии подключаем таймер диалога и наполняем поля ---
end = text.rstrip()
assert end.endswith("КонецПроцедуры"), "ожидался КонецПроцедуры в конце файла"
insert = (
    '\t\t// Диалог с нейросетью: собственный таймер 1 сек — отправка по тишине, '
    'приём ответа.\n'
    '\t\tПопытка\n'
    '\t\t\tПодключитьОбработчикОжидания("ПроверитьФразуДиалога", 1);\n'
    '\t\tИсключение\n'
    '\t\t\tСообщить("Диалог не запустился: " + ОписаниеОшибки());\n'
    '\t\t\tЗалогировать("chat timer error: " + ОписаниеОшибки());\n'
    '\t\tКонецПопытки;\n'
    '\t\tИстория = "Диалог с нейросетью (локальная модель Qwen через Ollama)." '
    '+ Символы.ПС\n'
    '\t\t\t+ "Напишите задачу, например: «покажи задолженность контрагентов» "\n'
    '\t\t\t+ "или «создай накладную на ООО Ромашка 5 шт по 200»." + Символы.ПС '
    '+ Символы.ПС;\n'
    '\t\tСтатус = "Готов. Ответ появится здесь через 1-2 секунды после фразы.";\n'
)
pos = end.rfind("КонецПроцедуры")
text = end[:pos] + insert + end[pos:]
P.write_text(text, encoding="utf-8-sig")
print("шаг 1/2: таймер диалога подключён, байт:", len(text.encode("utf-8")))
