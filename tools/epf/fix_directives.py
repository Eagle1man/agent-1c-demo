"""Проставляет корректные директивы компиляции в 1c/АгентМост.bsl для тонкого клиента (1cv8ct.exe).

Почему падало в тонком клиенте:
- ВыполнитьЗапрос1С использует `Новый Запрос` (тип существует только на сервере).
- ВыполнитьСоздатьДокумент использует `Метаданные`, `Справочники`, `Документы`,
  `РежимЗаписиДокумента` (доступны только на сервере).
- Чистые вспомогательные функции переводятся в &НаКлиентеНаСервереБезКонтекста,
  чтобы их можно было вызывать и с клиента, и с сервера.
- Серверные обработчики команд (ВыполнитьПроверкаСвязи, ВыполнитьЗапрос1С,
  ВыполнитьСоздатьДокумент, ОбработатьКоманду, Залогировать) переводятся в &НаСервере.
"""
import re
from pathlib import Path

path = Path(r"D:\agent-1c-demo\1c\АгентМост.bsl")
raw = path.read_bytes()
has_bom = raw.startswith(b"\xef\xbb\xbf")
text = raw.decode("utf-8-sig")

BOTH_NO_CTX = {
    "УбратьБОМ",
    "ПрочитатьФайлТекст",
    "ЗаписатьТекстАтомарно",
    "ТекущаяМеткаВремени",
    "ЗначениеВJSON",
    "ОчиститьНеопределено",
    "СформироватьОтвет",
    "ОшибкаСтруктура",
    "УбратьКомментарииИзЗапроса",
    "СтруктураВJSON",
    "ФайлСуществует",
}

SERVER_CTX = {
    "Залогировать",
    "ВыполнитьПроверкаСвязи",
    "ВыполнитьЗапрос1С",
    "ВыполнитьСоздатьДокумент",
    "ОбработатьКоманду",
}

CLIENT_ONLY = {
    "ОпросОчереди",
    "ЗапуститьМост",
    "ОстановитьМост",
    "ПриОткрытии",
    "КаталогДиалога",
    "ДобавитьВИсторию",
    "ОтправитьФразуВНейросеть",
    "ЗабратьОтветДиалога",
    "ПроверитьФразуДиалога",
    "ОтветитьНаФразуМестно",
}

def repl(match):
    old_dir = match.group(1)
    decl_line = match.group(2)
    name = match.group(3)
    if name in BOTH_NO_CTX:
        new_dir = "&НаКлиентеНаСервереБезКонтекста"
    elif name in SERVER_CTX:
        new_dir = "&НаСервере"
    elif name in CLIENT_ONLY:
        new_dir = "&НаКлиенте"
    else:
        raise SystemExit(f"Неизвестная процедура/функция: {name}")
    return f"{new_dir}\r\n{decl_line}"

pattern = re.compile(
    r"^(&[А-Яа-я]+)\r?\n((?:Процедура|Функция)\s+([A-Za-zА-Яа-я_0-9]+)\b[^\r\n]*)",
    re.M,
)

new_text, count = pattern.subn(repl, text)
print(f"обновлено директив: {count}")
assert count == 26, f"ожидалось 26, обновлено {count}"

data = new_text.encode("utf-8")
if has_bom:
    data = b"\xef\xbb\xbf" + data
path.write_bytes(data)
