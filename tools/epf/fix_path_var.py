"""Путь обмена: переменная модуля вместо реквизита формы.

Почему: реквизит формы ПутьКExchange после ПриОткрытии оказывается пустым —
тик опроса видит пустую строку, пишет лог в D:\\log и не читает команды
(проверено на живой 1С 01.11.2026). Поэтому путь хранится в переменной модуля
ПутьОбмена, а поле формы читается один раз при старте/по кнопке.
"""
from pathlib import Path

path = Path(r"D:\agent-1c-demo") / "1c" / "АгентМост.bsl"
raw = path.read_bytes()
has_bom = raw.startswith(b"\xef\xbb\xbf")
text = raw.decode("utf-8-sig").replace("\r\n", "\n")

# 1. Переменная модуля + функция чтения поля формы
text = text.replace(
    "&НаКлиенте\nПерем ОжиданиеСекунд;",
    "&НаКлиенте\nПерем ОжиданиеСекунд;\n&НаКлиенте\nПерем ПутьОбмена;",
    1,
)

# 2. Все обращения к пути в коде — через переменную модуля
text = text.replace("ПутьКExchange", "ПутьОбмена")
# ...кроме вызова метода формы: Элементы/реквизит не используется, но поле
# должно читаться. Возвращаем имя реквизита в двух местах ниже.

# 3. ПриОткрытии: прочитать поле, затем значение по умолчанию
old_open = (
    "\t// ★ единственное место значения по умолчанию; поле формы важнее\n"
    "\t\tПопытка\n"
    '\t\t\tЕсли СокрЛП(Строка(ПутьОбмена)) = "" Тогда\n'
    '\t\t\t\tПутьОбмена = "D:\\agent-1c-demo\\exchange";\n'
    "\t\t\tКонецЕсли;\n"
    "\t\tИсключение\n"
    "\t\tКонецПопытки;\n"
)
new_open = (
    "\t// ★ единственное место значения по умолчанию; поле формы важнее\n"
    "\t\tПопытка\n"
    "\t\t\tПутьОбмена = СокрЛП(Строка(ПутьКExchange));\n"
    "\t\tИсключение\n"
    "\t\t\tПутьОбмена = \"\";\n"
    "\t\tКонецПопытки;\n"
    '\t\tЕсли ПутьОбмена = "" Тогда\n'
    '\t\t\tПутьОбмена = "D:\\agent-1c-demo\\exchange";\n'
    "\t\tКонецЕсли;\n"
)
if old_open not in text:
    raise SystemExit("не найден блок ПриОткрытии")
text = text.replace(old_open, new_open, 1)

# 4. ЗапуститьМост: тоже читает поле
old_start = (
    "\t\t// Приоритет: поле формы (реквизит ПутьОбмена), затем значение по умолчанию (★ выше)\n"
    "\t\tПопытка\n"
    "\t\t\tЗначПоля = ПутьОбмена;\n"
    '\t\t\tЕсли ЗначПоля <> Неопределено И СокрЛП(Строка(ЗначПоля)) <> "" Тогда\n'
    "\t\t\t\tПутьОбмена = СокрЛП(Строка(ЗначПоля));\n"
    "\t\t\tКонецЕсли;\n"
    "\t\tИсключение\n"
    "\t\tКонецПопытки;\n"
)
new_start = (
    "\t\t// Приоритет: поле формы, затем текущее значение\n"
    "\t\tПопытка\n"
    "\t\t\tЗначПоля = СокрЛП(Строка(ПутьКExchange));\n"
    '\t\t\tЕсли ЗначПоля <> "" Тогда\n'
    "\t\t\t\tПутьОбмена = ЗначПоля;\n"
    "\t\t\tКонецЕсли;\n"
    "\t\tИсключение\n"
    "\t\tКонецПопытки;\n"
)
if old_start not in text:
    raise SystemExit("не найден блок ЗапуститьМост")
text = text.replace(old_start, new_start, 1)

# 5. Залогировать пишет файл — переводим в клиентский контекст,
#    чтобы видеть ПутьОбмена (серверные методы не видят переменные клиента).
text = text.replace(
    "&НаСервере\nПроцедура Залогировать(ТекстСообщения) Экспорт",
    "&НаКлиенте\nПроцедура Залогировать(ТекстСообщения) Экспорт",
    1,
)

data = text.replace("\n", "\r\n").encode("utf-8")
if has_bom:
    data = b"\xef\xbb\xbf" + data
path.write_bytes(data)
print("путь переведён в переменную модуля; ПутьОбмена:", text.count("ПутьОбмена"))
