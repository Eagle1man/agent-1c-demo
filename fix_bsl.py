# -*- coding: utf-8 -*-
"""Разовый фикс 1c/АгентМост.bsl (Cline, по итогам приёмки verify_1c.py).

1) переносит ВСЮ логику из модуля объекта в модуль формы (переносом, не копией):
   форма внешней обработки не имеет гарантированной ссылки на модуль объекта,
   а ПодключитьОбработчикОжидания ищет процедуру только в своём модуле;
2) убирает несуществующий вызов ВерсияПлатформы() (ошибка компиляции);
3) оставляет ЕДИНСТВЕННУЮ строку пути по умолчанию (★) в модуле формы;
4) пишет UTF-8 с BOM, CRLF — как требует приёмка.

Запуск: py -3 fix_bsl.py   (повторный запуск безопасен — выходит со словом «уже»)
"""
from pathlib import Path

BSL = Path(__file__).resolve().parent / "1c" / "АгентМост.bsl"
OBJ_MARK = "// === МОДУЛЬ ОБЪЕКТА ==="
FORM_MARK = "// === МОДУЛЬ ФОРМЫ ==="
LOGIC_START = "Функция УбратьБОМ"
DEFAULT_PATH = "C:\\1c_agent\\exchange"

text = BSL.read_bytes().decode("utf-8-sig").replace("\r\n", "\n")
if "Перем ПутьКExchange;\n" in text and "Функция УбратьБОМ" in text[text.find(FORM_MARK):]:
    print("уже исправлено — выход")
    raise SystemExit(0)

i_form = text.find(FORM_MARK)
part_obj = text[:i_form]
i_logic = part_obj.find(LOGIC_START)
assert i_form > 0 and i_logic > 0, "не найдены маркеры модулей/логики"
logic = part_obj[i_logic:].rstrip() + "\n"

# --- фикс несуществующей функции (в логике, до переноса) ---
old_ver = ('\t\tПопытка\n\t\t\tПлатф = ВерсияПлатформы();\n\t\tИсключение\n'
           '\t\t\tПлатф = "8.3";\n\t\tКонецПопытки;')
new_ver = ('\t\t// Глобальной функции ВерсияПлатформы в 1С нет — учебная версия 8.3\n'
           '\t\tПлатф = "8.3";')
assert old_ver in logic, "не найден блок ВерсияПлатформы"
logic = logic.replace(old_ver, new_ver)

# --- модуль объекта: тонкий ---
obj_new = f'''{OBJ_MARK}
// АгентМост 1.0 — файловый мост «агент <-> 1С», протокол v1.0 (PROTOCOL.md).
// Вся рабочая логика, кнопки и таймер — в МОДУЛЕ ФОРМЫ: форма внешней обработки
// не имеет гарантированной ссылки на этот модуль, а ПодключитьОбработчикОжидания
// ищет процедуру только в своём модуле.
Перем ПутьКExchange Экспорт;

'''

# --- модуль формы: шапка + Перем + логика + кнопки ---
form_head = f'''{FORM_MARK}
// «АгентМост»: поле пути, кнопки «Запустить/Остановить мост», таймер и вся
// логика обмена по протоколу v1.0. Кодировка обмена — UTF-8 (см. PROTOCOL.md).
// ★ ЕДИНСТВЕННОЕ МЕСТО ДЛЯ ПРАВКИ ПУТИ (значение по умолчанию): "{DEFAULT_PATH}"
// Путь также можно задать полем формы «ПутьКExchange» — оно важнее значения ниже.
Перем ПутьКExchange;

'''

part_form = text[i_form:]
i_btn = part_form.find("Процедура ЗапуститьМост")
assert i_btn > 0, "нет ЗапуститьМост"
buttons = part_form[i_btn:]


def slice_proc(src, header):
    """Тело процедуры от заголовка до ближайшего КонецПроцедуры включительно."""
    a = src.find(header)
    assert a >= 0, header
    b = src.find("КонецПроцедуры", a)
    assert b > a, header
    return src[a:b + len("КонецПроцедуры")]


stop_old = slice_proc(buttons, "Процедура ОстановитьМост")

start_new = f'''Процедура ЗапуститьМост(Команда) Экспорт
\tПопытка
\t\t// Приоритет: поле формы, затем значение по умолчанию (★ выше)
\t\tПопытка
\t\t\tЕсли Элементы.Найти("ПутьКExchange") <> Неопределено Тогда
\t\t\t\tЗначПоля = Элементы.Найти("ПутьКExchange").Значение;
\t\t\t\tЕсли ЗначПоля <> Неопределено И СокрЛП(Строка(ЗначПоля)) <> "" Тогда
\t\t\t\t\tПутьКExchange = СокрЛП(Строка(ЗначПоля));
\t\t\t\tКонецЕсли;
\t\t\tКонецЕсли;
\t\tИсключение
\t\tКонецПопытки;
\t\tПодключитьОбработчикОжидания("ОпросОчереди", 2);
\t\tСообщить("Мост запущен. Опрос папки exchange каждые 2 сек: " + ПутьКExchange);
\t\tЗалогировать("Мост запущен: " + ПутьКExchange);
\tИсключение
\t\tСообщить("Не удалось запустить мост: " + ОписаниеОшибки());
\tКонецПопытки;
КонецПроцедуры'''

open_new = f'''Процедура ПриОткрытии(Отказ) Экспорт
\t// ★ единственное место значения по умолчанию; поле формы важнее
\t\tПутьКExchange = "{DEFAULT_PATH}";
\t\tЕсли Элементы.Найти("ПутьКExchange") <> Неопределено Тогда
\t\t\tЗначПоля = Элементы.Найти("ПутьКExchange").Значение;
\t\t\tЕсли ЗначПоля <> Неопределено И СокрЛП(Строка(ЗначПоля)) <> "" Тогда
\t\t\t\tПутьКExchange = СокрЛП(Строка(ЗначПоля));
\t\t\tКонецЕсли;
\t\tКонецЕсли;
КонецПроцедуры'''

buttons_new = start_new + "\n\n" + stop_old + "\n\n" + open_new + "\n"

# ★ единственное место строки пути: убираем дубль из перенесённого ОпросОчереди
old_fallback = ('\t\tЕсли ПутьКExchange = Неопределено Или ПутьКExchange = "" Тогда\n'
                f'\t\t\tПутьКExchange = "{DEFAULT_PATH}";\n\t\tКонецЕсли;\n')
assert old_fallback in logic, "нет fallback-пути в ОпросОчереди"
logic = logic.replace(old_fallback,
                      '\t\tЕсли ПутьКExchange = Неопределено Или ПутьКExchange = "" Тогда\n'
                      '\t\t\tЗалогировать("Путь к exchange не задан — пропуск опроса");\n'
                      '\t\t\tВозврат;\n\t\tКонецЕсли;\n', 1)

new_text = obj_new + form_head + logic + "\n" + buttons_new
assert "ВерсияПлатформы()" not in new_text
assert new_text.count(DEFAULT_PATH) == 2, new_text.count(DEFAULT_PATH)
assert "Процедура ОпросОчереди" in new_text[new_text.find(FORM_MARK):]
assert "ПодключитьОбработчикОжидания" in new_text

out = b"\xef\xbb\xbf" + new_text.replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8")
BSL.write_bytes(out)
print(f"OK: записано {len(out)} байт, строк: {new_text.count(chr(10)) + 1}")